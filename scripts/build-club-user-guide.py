def set_run_font(run, name: str = "Calibri", size: int | None = None, bold: bool = False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    if size:
        run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = NAVY if bold else RGBColor(0x1E, 0x29, 0x3B)


def add_para(doc: Document, text: str, *, size=11, bold=False, space_after=8, align="justify"):
    p = doc.add_paragraph()
    if align == "justify":
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    elif align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "right":
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    return p


def build_docx() -> None:
    doc = Document()
    for section in doc.sections:
        section.top_margin = Cm(2.0)
        section.bottom_margin = Cm(2.0)
        section.left_margin = Cm(2.2)
        section.right_margin = Cm(2.2)
        section.page_width = Cm(21.0)
        section.page_height = Cm(29.7)

    t = doc.add_paragraph()
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = t.add_run("TeamSuite")
    set_run_font(r, size=28, bold=True)
    st = doc.add_paragraph()
    st.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = st.add_run("Οδηγός λειτουργιών και ρυθμίσεων για συλλόγους")
    set_run_font(r, size=16, bold=True)
    add_para(
        doc,
        f"Πλήρης περιγραφή μενού, καρτελών, δημόσιων φορμών, αδειών αθλητών και αντιγράφων ασφαλείας.\n{APP_URL}\n{GUIDE_DATE}",
        size=11,
        align="center",
        space_after=16,
    )
    add_para(
        doc,
        "Ο οδηγός απευθύνεται στη διοίκηση και τη γραμματεία του συλλόγου. Δεν αντικαθιστά νομική συμβουλή (GDPR, καταστατικό, όροι Viva/τράπεζας).",
        size=10,
        align="justify",
    )

    add_para(doc, "Περιεχόμενα", size=14, bold=True, align="left", space_after=6)
    for sec in SECTIONS:
        if sec["level"] == 1:
            add_para(doc, sec["title"], size=11, bold=False, align="left", space_after=2)
        elif sec["level"] == 2:
            add_para(doc, "    " + sec["title"], size=10, align="left", space_after=1)

    for sec in SECTIONS:
        h = doc.add_heading(sec["title"], level=sec["level"])
        for run in h.runs:
            set_run_font(run, size=16 if sec["level"] == 1 else 13, bold=True)
        for para in sec.get("text") or []:
            add_para(doc, para)
        items = sec.get("items") or []
        if items:
            for item in items:
                p = doc.add_paragraph(style="List Bullet")
                p.clear()
                run = p.add_run(item)
                set_run_font(run, size=11)
                p.paragraph_format.space_after = Pt(4)

    footer = doc.sections[0].footer
    fp = footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fr = fp.add_run(f"TeamSuite — εμπιστευτικό για χρήση συλλόγου — {GUIDE_DATE}")
    set_run_font(fr, size=8)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    doc.save(DOCX_PATH)


