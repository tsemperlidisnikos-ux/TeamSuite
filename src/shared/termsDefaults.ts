/** Ensure privacy terms include the current AMKA section (migrates older short copy). */
export function ensureAmkaPrivacySection(html: string): { html: string; changed: boolean } {
  const trimmed = html.trim();
  if (!trimmed) return { html: '', changed: false };

  let next = trimmed
    .replace(/<h3>\s*Διατήρηση και Διαγραφή\s*<\/h3>\s*<p>[\s\S]*?<\/p>/i, '')
    .replace(/<h3>\s*Δικαιώματα Χρήστη\s*<\/h3>\s*<p>[\s\S]*?<\/p>/i, '');
  const strippedRetention = next !== trimmed;
  next = next.replace(/\n{3,}/g, '\n\n').trim();

  if (next.includes('Συλλογή και Επεξεργασία ΑΜΚΑ')) {
    return { html: next, changed: strippedRetention };
  }
  const withoutOld = next
    .replace(/<h3>\s*Επεξεργασία ΑΜΚΑ\s*<\/h3>[\s\S]*?(?=<h3>|$)/i, '')
    .trim();
  return {
    html: `${withoutOld}\n${AMKA_PRIVACY_SECTION_HTML}`.trim(),
    changed: true,
  };
}
