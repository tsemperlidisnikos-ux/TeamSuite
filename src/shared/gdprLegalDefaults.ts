export const PLATFORM_PAYMENT_NOTICE_HTML = `
<h1>Ενημέρωση για Δεδομένα Πληρωμών</h1>
<p>Οι πληρωμές με κάρτα διεκπεραιώνονται από την <strong>Viva Wallet</strong>. Η SportSuite 360 <strong>δεν αποθηκεύει</strong> αριθμό κάρτας, CVV ή πλήρη στοιχεία πληρωμής PCI. Αποθηκεύονται μόνο: κωδικός παραγγελίας, αναγνωριστικό συναλλαγής, ποσό, κατάσταση και ημερομηνία.</p>
`.trim();

export type PublicLegalDocId =
  | 'privacy'
  | 'cookies'
  | 'breach'
  | 'ropa'
  | 'payment'
  | 'terms';

export function getPublicLegalHtml(doc: PublicLegalDocId, termsHtml?: string): string {
  switch (doc) {
    case 'privacy':
      return PLATFORM_PRIVACY_POLICY_HTML;
    case 'cookies':
      return PLATFORM_COOKIE_POLICY_HTML;
    case 'breach':
      return PLATFORM_BREACH_PLAN_HTML;
    case 'ropa':
      return PLATFORM_ROPA_HTML;
    case 'payment':
      return PLATFORM_PAYMENT_NOTICE_HTML;
    case 'terms':
      return termsHtml?.trim() || '<p>Οι όροι χρήσης ορίζονται από τον σύλλογο στις Ρυθμίσεις.</p>';
    default:
      return PLATFORM_PRIVACY_POLICY_HTML;
  }
}
